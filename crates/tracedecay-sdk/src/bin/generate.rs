/// Format emitted Rust through the pinned toolchain's rustfmt. Failing loudly
/// is deliberate: unformatted output would put the fmt gate and the codegen
/// drift gate in permanent tension.
fn rustfmt(contents: &str) -> Result<String, Box<dyn Error>> {
    use std::io::Write as _;
    use std::process::{Command, Stdio};
    let mut child = Command::new("rustfmt")
        .args(["--edition", "2024", "--emit", "stdout"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .spawn()?;
    child
        .stdin
        .take()
        .ok_or("rustfmt stdin unavailable")?
        .write_all(contents.as_bytes())?;
    let output = child.wait_with_output()?;
    if !output.status.success() {
        return Err(format!("rustfmt failed with {}", output.status).into());
    }
    Ok(String::from_utf8(output.stdout)?)
}

fn write(path: &Path, contents: &str) -> Result<(), Box<dyn Error>> {
    fs::create_dir_all(path.parent().ok_or("generated path has no parent")?)?;
    fs::write(path, contents)?;
    Ok(())
}

fn quote(value: &str) -> String {
    format!("\"{}\"", value.replace('\\', "\\\\").replace('"', "\\\""))
}

#[cfg(test)]
mod tests {
    use serde_json::json;
    use tracedecay_tool_catalog::ExecutableBindingRegistryV1;

    use super::{
        canonical_operations, canonical_unavailable_operations, render_operations,
        render_schema_type,
    };

    #[test]
    fn schema_body_drives_typescript_request_and_result_types() {
        let schema = json!({
            "type": "object",
            "properties": {
                "name": { "type": "string" },
                "state": { "enum": ["available", "partial", "unavailable"] },
                "tags": { "type": "array", "items": { "type": "string" } }
            },
            "required": ["name", "state"],
            "additionalProperties": false
        });

        assert_eq!(
            render_schema_type(&schema).unwrap(),
            "{ readonly name: string; readonly state: \"available\" | \"partial\" | \"unavailable\"; readonly tags?: readonly string[] }"
        );
    }

    #[test]
    fn unsupported_schema_keywords_fail_closed() {
        let schema = json!({
            "type": "object",
            "unevaluatedProperties": false
        });

        assert!(render_schema_type(&schema).is_err());
    }

    #[test]
    fn absent_application_registry_assembly_exports_no_operations() {
        let registry = ExecutableBindingRegistryV1::new(Vec::new()).unwrap();
        let operations = canonical_operations(&registry).unwrap();
        let unavailable = canonical_unavailable_operations(&registry);

        assert!(operations.is_empty());
        let generated = render_operations(&operations, &unavailable).unwrap();
        assert!(generated.contains("export const OPERATIONS = [] as const;"));
        assert!(!generated.contains("route: \"/"));
    }
}
