import assert from 'node:assert/strict';
import { chromium } from 'playwright';
const browser=await chromium.launch();
const base=process.env.BASE_URL ?? 'http://127.0.0.1:5195';
try {
 const page=await browser.newPage({viewport:{width:1280,height:720}}), errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 const go=async extra=>{await page.goto(`${base}/?surface=loom&data=fixture&loom_source=design&state=04&loom_page=full&loom_lens=proximity${extra}`);await page.locator('.proximity-lens').waitFor();};
 const params=()=>new URL(page.url()).searchParams;
 await go('');
 assert.equal(await page.locator('.proximity-strand').count(),123);
 assert.equal(await page.locator('.proximity-encounters button').count(),6);
 assert.equal(await page.locator('.journey-minimap [data-proximity-session]').count(),123);
 assert.equal(await page.locator('.journey-minimap [data-proximity-encounter]').count(),12);
 await page.locator('.proximity-encounters button').filter({hasText:'prospective integration'}).click();
 assert.match(await page.locator('.proximity-detail').innerText(),/SEPARATE WORKTREES.*no on-disk overwrite/);
 assert.match(await page.locator('.proximity-detail').innerText(),/COMMON BASE/);
 await page.getByRole('button',{name:'REPLAY OBSERVATION',exact:true}).click();
 assert.equal(params().get('loom_replay'),'1');
 assert.doesNotMatch(await page.locator('.proximity-description').innerText(),/STALE/);
 await page.getByRole('button',{name:'← BACK TO OVERVIEW',exact:true}).click();
 assert.equal(await page.locator('.proximity-encounters button').count(),4,'Only observations known at the cursor appear');
 await page.locator('.proximity-encounters button').filter({hasText:'prospective integration'}).click();
 await page.getByRole('button',{name:'FOCUS LOCAL INTERVAL',exact:true}).click();
 const before=new URL(page.url());
 await page.locator('.proximity-pair a').first().click();
 await page.getByRole('link',{name:/RETURN TO LOOM/i}).click();
 assert.equal(params().get('loom_encounter'),before.searchParams.get('loom_encounter'));
 for(const key of ['loom_from','loom_to','loom_time'])assert.equal(params().get(key),before.searchParams.get(key),'Exact encounter camera and cursor restored');
 await go('&loom_replay=1&loom_time='+Date.parse('2025-05-12T14:36:55Z')/1000+'&loom_encounter=fixture:proximity:integration');
 assert.match(await page.locator('.proximity-description').innerText(),/STALE.*not resolved/);
 await go('&loom_replay=1&loom_time='+Date.parse('2025-05-12T14:20:00Z')/1000+'&loom_encounter=fixture:proximity:integration');
 assert.equal(await page.locator('.proximity-detail').count(),0,'Future encounter details are withheld');
 assert.match(await page.locator('.proximity-encounters h3').innerText(),/0$/);
 assert.equal(await page.locator('.journey-minimap [data-proximity-encounter]').count(),0);
 await page.goto(`${base}/?surface=loom&data=snapshot&loom_source=mac&state=04&loom_lens=proximity`);
 assert.match(await page.locator('.proximity-lens').innerText(),/does not export/);
 assert.equal(await page.locator('.proximity-pair').count(),0);
 await go('&loom_encounter=fixture:proximity:git-conflict');
 await page.getByRole('button',{name:'REPLAY OBSERVATION',exact:true}).click();
 await page.getByRole('button',{name:'FOCUS LOCAL INTERVAL',exact:true}).click();
 await page.getByRole('slider',{name:'Scrub loaded page',exact:true}).fill(String(Date.parse('2025-05-12T14:39:30Z')/1000));
 await page.setViewportSize({width:640,height:720});
 assert.ok(await page.getByRole('button',{name:'← BACK TO OVERVIEW',exact:true}).isVisible());
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 assert.deepEqual(errors,[]);
 console.log('PASS many-agent proximity, shared minimap geometry, replay withholding, expiry, exact source pivots and responsive detail');
}finally{await browser.close();}
