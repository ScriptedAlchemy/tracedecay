// Run: node --experimental-strip-types qa/tracked-workload.mjs
import assert from 'node:assert/strict';
import workload, { externalRelations, trackedRepositories, trackedBranches, trackingCoverage } from '../src/data/tracked-workload.ts';

assert.equal(trackingCoverage.state, 'partial');
assert.ok(Number.isFinite(Date.parse(trackingCoverage.observedAt)));
assert.ok(trackingCoverage.reason.length > 0);
assert.ok(trackingCoverage.evidence.length > 0);
assert.equal(workload.branches, trackedBranches);
assert.equal(workload.trackedBranchCount, 1);
assert.equal(workload.prContextCount, 1);
assert.deepEqual(trackedRepositories, ['web-infra-dev/rspack']);
const [branch] = trackedBranches;
assert.equal(branch.kind, 'branch');
assert.equal(branch.graphSource.project_id, 'proj_175ebc47e48f0ec9');
assert.equal(branch.trackedRef, 'refs/remotes/origin/feat/mf-layers');
assert.equal(branch.graphSource.publication_epoch, 1);
assert.equal(branch.graphSource.source_oid, 'ecd6feb8cec8a3f936947d35f041271691e735b5');
assert.equal(Object.keys(branch.graphSource).length, 7);
assert.ok(Object.values(branch.graphSource).every(Boolean));
assert.equal(branch.prContext.enrollment, 'head-matched-context');
assert.equal(branch.prContext.repo, branch.repository);
assert.equal(branch.prContext.headSha, branch.graphSource.source_oid);
assert.equal(branch.trackedRef, `refs/remotes/origin/${branch.prContext.headRef}`);
assert.deepEqual(workload.prs.map(pr => pr.id), [branch.prContext.id]);
assert.equal(workload.prs[0].headSha, branch.graphSource.source_oid);
assert.ok(branch.sourceEvidence.length > 0);
assert.equal(branch.footprint.comparison, 'base-to-head');
assert.equal(branch.footprint.headOid, branch.graphSource.source_oid);
assert.equal(branch.footprint.baseOid, 'ba36b0ad179a7874d142b20a43c87f268df7d652');
assert.equal(new Set(branch.footprint.files.map(file => file.path)).size, branch.footprint.files.length);
assert.equal(branch.footprint.files.length, 117);
assert.equal(branch.footprint.files.reduce((sum, file) => sum + (file.additions ?? 0), 0), 2840);
assert.equal(branch.footprint.files.reduce((sum, file) => sum + (file.deletions ?? 0), 0), 685);
assert.ok(branch.footprint.files.every(file => [file.additions, file.deletions].every(value => value === null || Number.isInteger(value) && value >= 0)));
assert.equal(workload.capturedAt, trackingCoverage.observedAt);
assert.equal(branch.observedAt, trackingCoverage.observedAt);
assert.deepEqual(workload.relations, []);
assert.deepEqual(workload.reviewActivity, []);
assert.deepEqual(externalRelations, []);
assert.deepEqual(workload.source.queries, []);
assert.ok(Object.values(workload.counts).every(count => count === null));
assert.equal(workload.trackingCoverage, trackingCoverage);
assert.equal(Date.parse(workload.window.end) - Date.parse(workload.window.start), 7 * 86400000);
console.log('One indexed branch admits only its exact-head-matched PR context; full workload totals and uncaptured review/check evidence remain unknown.');
