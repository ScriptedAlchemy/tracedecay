#!/usr/bin/env bash
# Runs the storage contention benchmark in fresh processes, appends one JSON
# line per shape and run to benchmark_data/storage-concurrency/results.jsonl,
# and regenerates MEASUREMENTS.md from every recorded row.
#
# Usage: scripts/run-storage-contention-benchmark.sh [--native] [runs]
#   --native  build the owned-store engine as native Turso (--config=native)
#   runs      fresh benchmark processes to record (default 5)
# BAZEL overrides the bazel executable.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$root"
data=benchmark_data/storage-concurrency
config=()
if [[ "${1:-}" == --native ]]; then
  config=(--config=native)
  shift
fi
runs="${1:-5}"

if [[ -n "$(git status --porcelain -- . ":!$data")" ]]; then
  echo "refusing to record results from a dirty tree; commit first" >&2
  exit 1
fi
sha="$(git rev-parse HEAD)"
host="$(hostname)"

for run in $(seq "$runs"); do
  echo "run $run/$runs at $sha" >&2
  "${BAZEL:-bazel}" test "${config[@]}" //crates/tracedecay-rusqlite-runtime:storage_contention \
    --nocache_test_results --test_output=streamed --test_arg=--bench \
    --test_env=TRACEDECAY_BENCH_SOURCE_SHA="$sha" \
    --test_env=TRACEDECAY_BENCH_HOST="$host" |
    grep '^{' >>"$data/results.jsonl"
done

python3 - "$data" <<'PY'
import json
import pathlib
import statistics
import sys

data = pathlib.Path(sys.argv[1])
rows = [json.loads(line) for line in (data / "results.jsonl").read_text().splitlines() if line]
groups = {}
for row in rows:
    groups.setdefault((row["source_sha"], row["host"], row["engine"]), {}).setdefault(row["shape"], []).append(row)

def median(runs, *path):
    values = []
    for run in runs:
        for key in path:
            run = run[key]
        values.append(run)
    return statistics.median(values)

out = [
    "# Storage contention measurements",
    "",
    "Generated by `scripts/run-storage-contention-benchmark.sh` from",
    "[results.jsonl](results.jsonl); do not edit by hand. Each cell is the median",
    "of per-run statistics over representative runs (one-minute load average at",
    "or below 200 at the start and end of the shape). When no run of a shape is",
    "representative, the median covers all runs and the row says so.",
]
for (sha, host, engine), shapes in groups.items():
    first = next(iter(shapes.values()))[0]
    out += [
        "",
        f"## {engine} at `{sha}`",
        "",
        f"Host `{host}`: {first['os']} {first['arch']}, {first['cpus']} CPUs, "
        f"debug assertions {'on' if first['debug_assertions'] else 'off'}.",
        "",
        "| Shape | Runs (representative) | Settled/s | Receipt p50 ms | p95 ms | p99 ms "
        "| Read p99 ms | Search p50 ms | Search p99 ms | Conflicts | In-flight retries | Load range |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for shape, runs in shapes.items():
        good = [run for run in runs if run["representative"]]
        used = good or runs
        loads = [load for run in runs for load in run["load_average_1m"].values() if load is not None]
        load_range = f"{min(loads):.0f}–{max(loads):.0f}" if loads else "n/a"
        label = f"{len(runs)} ({len(good)})" + ("" if good else ", none representative")
        out.append(
            f"| {shape} | {label} | {median(used, 'settled_per_s'):.1f} "
            f"| {median(used, 'receipt_latency', 'p50_ms'):.2f} "
            f"| {median(used, 'receipt_latency', 'p95_ms'):.2f} "
            f"| {median(used, 'receipt_latency', 'p99_ms'):.2f} "
            f"| {median(used, 'read_latency', 'p99_ms'):.3f} "
            f"| {median(used, 'search_latency', 'p50_ms'):.3f} "
            f"| {median(used, 'search_latency', 'p99_ms'):.3f} "
            f"| {median(used, 'outcomes', 'idempotency_conflict'):.0f} "
            f"| {median(used, 'retries', 'in_flight'):.0f} | {load_range} |"
        )
(data / "MEASUREMENTS.md").write_text("\n".join(out) + "\n")
PY
