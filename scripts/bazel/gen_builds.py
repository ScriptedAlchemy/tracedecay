#!/usr/bin/env python3
"""Generate Bazel BUILD files for the Cargo workspace.

Reads `cargo metadata` for target shapes and `cargo tree` for Cargo's own
feature resolution, then emits one BUILD.bazel per member crate under
crates/. The lane resolves the Linux dependency graph only: member deps'
cfg() target gates are evaluated against a generic Linux host, and a gate
whose answer depends on the machine aborts the generator instead of
silently drifting (see cfg_applies_linux).

Filegroups for sources living outside a member's package land in the owning
package's BUILD.bazel. Member packages get them appended to their generated
rules; other packages keep handwritten content and carry the generated
rules inside a marked GEN_BEGIN/GEN_END block the generator re-renders, so
stale or obsolete groups are detectable drift rather than inherited bytes.

Feature model. Cargo compiles a member once per resolved feature set, and the
set depends on the consuming context (normal build vs dev/test resolution vs
required-features). Test contexts resolve once across the whole workspace,
as one `cargo test --workspace` does, so every member's tests share one
dependency build. Each member gets one rust_library per distinct feature set it is ever
built with. `<pkg>` covers its own build context and
`<pkg>__<extra-features>` names the variants. A variant's own member deps are the union
of the labels every producing context resolves for them. Dependents pick the
variant matching the feature set Cargo resolves in their context.

Outputs are deterministic. Rerun after any Cargo.toml change. `--check`
verifies the committed BUILD.bazel files match a fresh run without writing.
"""

