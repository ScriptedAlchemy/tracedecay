            '    compile_data = glob(["**"], allow_empty = True, exclude = ["**/* *", ".tmp_git_root/**/*", "BUILD", "BUILD.bazel", "WORKSPACE", "WORKSPACE.bazel"]),\n'
            f'    crate_features = [{q(features)}],\n'
            f'    crate_name = "{lib["name"].replace("-", "_")}",\n'
            f'    crate_root = "{crate_root}",\n'
            f'    edition = "{package["edition"]}",\n'
            '    rustc_flags = ["--cap-lints=allow"],\n'
            f'    tags = ["cargo-bazel", "crate-name={name}", "manual", "noclippy", "norustfmt"],\n'
            f'    version = "{version}",\n'
            f"    deps = [{q(dep_labels)}],\n"
            ")\n"
            '""",\n'
            f'    crate = "{name}",\n'
            f'    override_target_lib = "@{repo}//:{target}",\n'
            f'    version = "{version}",\n'
            ")\n"
            # The root module resolves the override label, so it needs the
