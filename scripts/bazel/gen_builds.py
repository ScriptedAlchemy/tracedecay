_CFG_TOKEN = re.compile(r'"(?:[^"\\]|\\.)*"|[A-Za-z_][A-Za-z0-9_.]*|[(),=]')


def _cfg_parse(source):
    """Cargo cfg() expression -> ('all'|'any'|'not', [nodes]) | ('flag', name)
    | ('kv', key, value). Raises ValueError on any other shape."""
    tokens = []
    pos = 0
    while pos < len(source):
        if source[pos].isspace():
            pos += 1
            continue
        match = _CFG_TOKEN.match(source, pos)
        if not match:
            raise ValueError(source)
        tokens.append(match.group(0))
        pos = match.end()
    pos = 0

    def expression():
        nonlocal pos
        if pos >= len(tokens):
            raise ValueError(source)
        token = tokens[pos]
        pos += 1
        if token in ("all", "any", "not") and pos < len(tokens) and tokens[pos] == "(":
            pos += 1
            children = []
            while pos < len(tokens) and tokens[pos] != ")":
                children.append(expression())
                if pos < len(tokens) and tokens[pos] == ",":
                    pos += 1
                else:
                    break
            if pos >= len(tokens) or tokens[pos] != ")":
                raise ValueError(source)
            pos += 1
            if not children or (token == "not" and len(children) != 1):
                raise ValueError(source)
            return (token, children)
        if token in ("(", ")", ",", "=") or token.startswith('"'):
            raise ValueError(source)
        if pos < len(tokens) and tokens[pos] == "=":
            pos += 1
            if pos >= len(tokens) or not tokens[pos].startswith('"'):
                raise ValueError(source)
            try:
                value = json.loads(tokens[pos])
            except ValueError:
                raise ValueError(source) from None
            pos += 1
            return ("kv", token, value)
        return ("flag", token)

    tree = expression()
    if pos != len(tokens):
        raise ValueError(source)
    return tree


def _cfg_eval(node):
    """Tri-state Cargo cfg evaluation for a generic Linux host: True/False
    when the answer is platform-fixed, None when it depends on the machine
    (target_arch, target_env, target_abi, endian, pointer width, vendor,
    target_feature, panic, feature)."""
    op = node[0]
    if op == "flag":
        return {"unix": True, "windows": False}.get(node[1])
    if op == "kv":
        key, value = node[1], node[2]
        if key == "target_os":
            return value == "linux"
        if key == "target_family":
            # unix admits the lane; the other Cargo families never do.
            return {"unix": True, "windows": False, "wasm": False}.get(value)
        return None
    verdicts = [_cfg_eval(child) for child in node[1]]
    if op == "not":
        return None if verdicts[0] is None else not verdicts[0]
    if op == "any":
        if True in verdicts:
            return True
        return None if None in verdicts else False
    if False in verdicts:
        return False
    return None if None in verdicts else True


def cfg_applies_linux(target):
    """Whether a member dep's Cargo target gate admits it on Linux.

    The generated graph is the Linux resolution only: cfg() gates are
    evaluated as Cargo does — nested all/any/not included — and a gate whose
    answer depends on the host aborts the generator instead of baking one
    machine's graph into the tree."""
    if target is None:
        return True
    t = target.strip()
    if not t.startswith("cfg("):
        # A concrete target triple admits the dep only on a matching Linux.
        return "linux" in t
    verdict = None
    if t.endswith(")"):
        try:
            verdict = _cfg_eval(_cfg_parse(t[4:-1]))
        except ValueError:
            pass
    if verdict is None:
        sys.exit(
            f"gen_builds.py: member dependency target gate {target!r} is not "
            "resolvable for a generic Linux host; the Bazel lane resolves "
            "the Linux dependency graph only, so decide the mapping "
            "explicitly"
        )
    return verdict


def variant_name(pkg, feats, base):
    """Target name for a feature-set variant. `+feats`/`-feats` vs the
    member's own build-context set. `__bare` when nothing resolves."""
    if feats == base:
        return pkg
    if not feats:
        return f"{pkg}__bare"
    suffix = []
    plus = sorted(feats - base)
    minus = sorted(base - feats)
    if plus:
        suffix.extend(f"+{f}" for f in plus)
    if minus:
        suffix.extend(f"-{f}" for f in minus)
    name = f"{pkg}__{'_'.join(suffix)}"
    if len(name) > 120:
        name = f"{pkg}__cfg_{hashlib.sha1(','.join(sorted(feats)).encode()).hexdigest()[:8]}"
    return name


def q(items):
    return ", ".join(json.dumps(i) for i in items)


def env_dict(env):
    """A Starlark dict literal with sorted keys."""
    return "{" + ", ".join(
        f"{json.dumps(k)}: {json.dumps(v)}" for k, v in sorted(env.items())
    ) + "}"


@lru_cache(maxsize=None)
def rust_sources(roots):
    """(path, text) for every .rs file under `roots`, read once per run: the
    per-target scans below all walk the same test and #[path] trees."""
    seen = {}
    for root in roots:
        for f in root.rglob("*.rs"):
            seen.setdefault(f, f.read_text(errors="replace"))
    return tuple(seen.items())


def target_sources(t, extra_dirs=()):
    return rust_sources((Path(t["src_path"]).resolve().parent, *extra_dirs))


